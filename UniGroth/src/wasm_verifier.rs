#[cfg(test)]
mod tests {
    use super::*;
    use crate::Groth16;
    use ark_bn254::{Bn254, Fr};
    use ark_crypto_primitives::snark::SNARK;
    use ark_relations::{
        gr1cs::{ConstraintSynthesizer, ConstraintSystemRef, SynthesisError},
        lc,
    };
    use ark_std::rand::{RngCore, SeedableRng};

    fn make_rng() -> ark_std::rand::rngs::StdRng {
        ark_std::rand::rngs::StdRng::seed_from_u64(ark_std::test_rng().next_u64())
    }

    #[derive(Clone)]
    struct MulCircuit {
        a: Option<Fr>,
        b: Option<Fr>,
    }

    impl ConstraintSynthesizer<Fr> for MulCircuit {
        fn generate_constraints(self, cs: ConstraintSystemRef<Fr>) -> Result<(), SynthesisError> {
            let a = cs.new_witness_variable(|| self.a.ok_or(SynthesisError::AssignmentMissing))?;
            let b = cs.new_witness_variable(|| self.b.ok_or(SynthesisError::AssignmentMissing))?;
            let c_val = self.a.unwrap_or_default() * self.b.unwrap_or_default();
            let c = cs.new_input_variable(|| Ok(c_val))?;
            cs.enforce_r1cs_constraint(|| lc!() + a, || lc!() + b, || lc!() + c)?;
            Ok(())
        }
    }

    #[test]
    fn test_wasm_generation() {
        let mut rng = make_rng();
        let (_, vk) =
            Groth16::<Bn254>::circuit_specific_setup(MulCircuit { a: None, b: None }, &mut rng)
                .unwrap();

        let src = generate_wasm_verifier(&vk, "test_mul");
        assert!(src.contains("verify_proof"));
        assert!(src.contains("wasm_bindgen"));
        assert!(src.contains("NUM_PUBLIC_INPUTS: usize = 1"));
        assert!(src.contains("deserialize_compressed"));
        assert!(src.contains("multi_miller_loop"));
    }

    #[test]
    fn test_wasm_cargo_toml() {
        let toml = generate_wasm_cargo_toml("my_circuit");
        assert!(toml.contains("my_circuit-verifier"));
        assert!(toml.contains("wasm-bindgen"));
        assert!(toml.contains("ark-bn254"));
    }

    #[test]
    fn test_wasm_size_estimate() {
        let est = estimate_wasm_size(5);
        assert!(est.total_estimate_kb > 0);
        assert_eq!(est.num_public_inputs, 5);
    }
}
