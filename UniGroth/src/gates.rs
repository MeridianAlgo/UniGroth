    #[test]
    fn test_sha256_gate_constraint_count() {
        let sigma0 = Sha256SigmaGate::new(Sha256GateType::UpperSigma0);
        assert_eq!(
            sigma0.constraint_count(),
            160,
            "Σ0 should have 160 constraints"
        );

        let sigma1 = Sha256SigmaGate::new(Sha256GateType::UpperSigma1);
        assert_eq!(
            sigma1.constraint_count(),
            144,
            "Σ1 should have 144 constraints"
        );

        let lower0 = Sha256SigmaGate::new(Sha256GateType::LowerSigma0);
        assert_eq!(
            lower0.constraint_count(),
            120,
            "σ0 should have 120 constraints"
        );

        let lower1 = Sha256SigmaGate::new(Sha256GateType::LowerSigma1);
        assert_eq!(
            lower1.constraint_count(),
            128,
            "σ1 should have 128 constraints"
        );

        // All variants must be strictly below the naive baseline.
        for gate in [&sigma0, &sigma1, &lower0, &lower1] {
            assert!(
                gate.constraint_count() < gate.naive_constraint_count(),
                "Custom gate must beat naive for {:?}",
                gate.gate_type
            );
        }

        // Word bits is always 32.
        assert_eq!(sigma0.word_bits, 32);
    }

    #[test]
    fn test_ec_add_gate_fewer_than_naive() {
        let gate = EcAddGate::new();
        assert!(
            gate.constraint_count() < 15,
            "EcAddGate must use fewer than 15 constraints (got {})",
            gate.constraint_count()
        );
        assert_eq!(gate.constraint_count(), 5);
        assert_eq!(gate.wire_count(), 7);
        assert_eq!(gate.naive_constraint_count(), 15);
        assert_eq!(gate.savings(), 10);

        // Symbolic output should be non-empty.
        let sym = gate.add_constraints_symbolic();
        assert!(!sym.is_empty());
        assert!(sym.contains("lambda"));
    }

